const { chromium } = require('playwright'); const fs = require('fs'); const http = require('http'); const path = require('path');
const root = path.resolve(__dirname, '../../www'); // needs: npm i -D playwright
const srv = http.createServer((q, r) => {
  const f = q.url === '/calib.html' ? path.join(__dirname, 'calib.html') : path.join(root, q.url);
  r.setHeader('Content-Type', f.endsWith('.js') ? 'text/javascript' : 'text/html'); r.end(fs.readFileSync(f));
}).listen(8765, async () => {
  const b = await chromium.launch(); const p = await b.newPage();
  p.on('console', m => console.log('console', m.text())); p.on('pageerror', e => console.log('ERR', e.message));
  await p.goto('http://localhost:8765/calib.html');
  const res = await p.waitForFunction(() => window.RESULT, null, { timeout: 300000 }).then(h => h.jsonValue());
  console.table(res.info);
  fs.writeFileSync(root + '/js/calib.js', '// Generated by measuring each layer offline: equalises loudness across layers.\nexport const CALIB = ' + JSON.stringify(res.out) + ';\n');
  await b.close(); srv.close();
});
